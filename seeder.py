def seed_pool(clear_existing=True):
    init_db()
    conn = get_conn()
    if clear_existing:
        cur = conn.cursor()
        cur.execute("DELETE FROM players")
        conn.commit()
        cur.close()
    conn.close()

    total = 0
    for pos, players in POOL.items():
        for name, base_m in players:
            add_player(name, pos, float(base_m))
            total += 1
    return total
